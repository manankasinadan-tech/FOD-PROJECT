val LocalFodStrings = staticCompositionLocalOf { EnglishFodStrings }

@Composable
fun resolveFodStrings(preference: LanguagePreference): FodStrings {
    return when (preference) {
        LanguagePreference.FRENCH -> FrenchFodStrings
        LanguagePreference.ENGLISH -> EnglishFodStrings
        LanguagePreference.SYSTEM -> {
            val lang = Locale.getDefault().language.lowercase()
            if (lang.startsWith("fr")) FrenchFodStrings else EnglishFodStrings
        }
    }
}
